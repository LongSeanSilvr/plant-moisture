# sprites.py — Plant sprite pixel data for the 64x32 LED Hub
#
# Palette (5 colors, bit_depth=1 requires Palette(5)):
#   0 = BLACK   (0x000000) — background
#   1 = GREEN   (0x00FF00) — healthy leaves
#   2 = YELLOW  (0xFFFF00) — thirsty leaves
#   3 = RED     (0xFF0000) — critical leaves / drooping
#   4 = BROWN   (0x884400) — terracotta pot
#
# Each sprite is 16 pixels wide x 20 pixels tall = 320 characters.
# Stored as 20 rows of 16 characters for human readability.
# Rows 0-13: plant design. Rows 14-19: pot (shared across all sprites).
#
# Pot rows (canonical, shared):
#   row 14: 0004444444444000
#   row 15: 0044444444444400
#   row 16: 0044444444444400
#   row 17: 0004444444444000
#   row 18: 0000000000000000
#   row 19: 0000000000000000

POT = (
    "0004444444444000"
    "0044444444444400"
    "0044444444444400"
    "0004444444444000"
    "0000000000000000"
    "0000000000000000"
)

